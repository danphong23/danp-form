# Regenerate the consolidated spec and documentation hashes from authoritative modules.
$ErrorActionPreference = 'Stop'
$docRoot = [System.IO.Path]::GetFullPath((Join-Path $PSScriptRoot '..'))
$utf8 = [System.Text.UTF8Encoding]::new($false)
$specPath = Join-Path $docRoot 'docs/full-specification.md'
$existingSpec = [System.IO.File]::ReadAllText($specPath)
$sourcePaths = @([regex]::Matches($existingSpec, '<!-- source: ([^\r\n]+) -->') | ForEach-Object { $_.Groups[1].Value })
$allModulePaths = @(Get-ChildItem -LiteralPath (Join-Path $docRoot 'docs') -Recurse -File -Filter '*.md' | Where-Object Name -ne 'full-specification.md' | Sort-Object FullName | ForEach-Object { [System.IO.Path]::GetRelativePath($docRoot, $_.FullName).Replace('\','/') })
if ($sourcePaths.Count -eq 0) { throw 'No source order in existing consolidated specification.' }
foreach ($relativePath in $sourcePaths) {
    if ($relativePath -notin $allModulePaths) { throw "Missing/invalid module: $relativePath" }
}
$sourcePaths = @($sourcePaths | Select-Object -Unique)
$sourcePaths += @($allModulePaths | Where-Object { $_ -notin $sourcePaths })
$specParts = @('# DANP Form — Full Specification', '> Generated from the modular documents listed below. Do not edit this file independently. Modular documents are authoritative.')
foreach ($relativePath in $sourcePaths) {
    $specParts += "---`n`n<!-- source: $relativePath -->`n`n" + [System.IO.File]::ReadAllText((Join-Path $docRoot $relativePath)).Trim()
}
[System.IO.File]::WriteAllText($specPath, ($specParts -join "`n`n") + "`n", $utf8)
$entries = @(Get-ChildItem -LiteralPath $docRoot -Recurse -File -Filter '*.md' | Where-Object {
    [System.IO.Path]::GetRelativePath($docRoot, $_.FullName).Replace('\','/') -notmatch '(^|/)(\.git|dist|__pycache__|\.pytest_cache|\.mypy_cache|\.ruff_cache)(/|$)'
} | Sort-Object FullName | ForEach-Object {
    [ordered]@{ path = [System.IO.Path]::GetRelativePath($docRoot, $_.FullName).Replace('\','/'); sha256 = (Get-FileHash -LiteralPath $_.FullName -Algorithm SHA256).Hash.ToLowerInvariant(); bytes = $_.Length }
})
[System.IO.File]::WriteAllText((Join-Path $docRoot 'docs-manifest.json'), (ConvertTo-Json -InputObject $entries -Depth 4) + "`n", $utf8)
[System.IO.File]::WriteAllText((Join-Path $docRoot 'MANIFEST_SHA256.txt'), (($entries | ForEach-Object { $_.sha256 + '  ' + $_.path }) -join "`n") + "`n", $utf8)
Write-Output ('Regenerated modules=' + $sourcePaths.Count + ', documentation hashes=' + $entries.Count)
